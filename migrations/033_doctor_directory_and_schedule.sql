-- NEGIS Migration 033 — у врача появляется своя строка, а у графика — своя таблица.
--
-- Сегодня «врач» в этом продукте записью не является. Единственное место, где он
-- сохраняется, — appointments.doctor_name из 010: свободный текст без связи,
-- который сервер принимает из тела запроса как есть и ни с чем не сверяет. А
-- список, из которого его выбирают, — четыре выдуманных имени в коде экрана
-- записей, объединённые с теми строками, что случайно загружены в браузер.
-- Отсюда всё остальное: «д-р Сауле» и «Д-р Сауле » — два разных врача в любом
-- подсчёте и два независимых календаря в проверке пересечений; нового врача
-- через форму записи ввести нельзя вообще, потому что поле — закрытый список;
-- а запись с пустым именем врача рисуется оператору как «д-р Сауле» — имя,
-- которого в базе нет.
--
-- Расписания нет ни в каком виде: ни таблицы, ни колонки, ни константы. Дневная
-- сетка захардкожена 09:00-21:00 с шагом 30 минут — одинаково для каждого врача
-- и каждого дня. Поэтому в миграции две половины: справочник, который даёт врачу
-- личность, и график, которому эту личность есть к чему привязать.
--
-- Имя справочника — clinic_doctors, парой к clinic_services. Не agents: это имя
-- жёстко перечислено в UNCREATED_LEGACY_TABLES набора test:migration-chain, а M3
-- сравнивает набор через deepEqual — объект с таким именем ломает набор по
-- построению, ровно как ломало бы имя services в 032.
--
-- Личность врача живёт здесь, а не в staff_users, и дело не в колонках: в
-- staff_users есть всё, что графику нужно. Причины две, и обе про людей. Первая:
-- попасть в staff_users можно только через приглашение, которое требует адрес
-- почты и человека, доказавшего контроль над ним, — приезжий врач, который в CRM
-- не заходит, строки не получит никогда. Вторая: читать staff_users вправе
-- только owner и admin, поэтому список врачей в форме записи оказался бы пуст
-- ровно у регистратора, который и записывает. Справочник свой, а связь с
-- сотрудником — необязательная колонка staff_user_id, для будущего «мой график».
--
-- Форма связи — снимок, дословно как в 032. appointments.doctor_name остаётся и
-- сервером не переписывается никогда: по нему строится фильтр записей, он
-- печатается на карточке и в журнале изменений, и по нему же — по строке, а не
-- по ссылке — продолжает работать проверка пересечений. Последнее записано
-- здесь намеренно, а не забыто: у всей уже накопленной истории doctor_id пуст, и
-- сужение проверки по ссылке молча сняло бы защиту от двойной записи на весь
-- переходный период.
--
-- Никакого бэкфилла, и довод здесь сильнее, чем у 032: четыре имени по умолчанию
-- выдуманы, а doctor_name никогда не нормализовалась. Сопоставление по точному
-- совпадению оставило бы большинство строк пустыми, а «умное» приписало бы
-- медицинский визит не тому врачу. Догадываться задним числом в медицинских
-- записях — не дело миграции. Старые строки живут со своим текстом и
-- doctor_id = NULL, и каждый экран продолжает показывать текст.
--
-- Часового пояса здесь нет ни одной колонки. Пояс принадлежит клинике, а не
-- врачу, и живёт значением в workspace_settings под ключом clinic_schedule:
-- таблица заведена в 013, а добавление строки схему не меняет. Дотянуться до
-- workspace_settings этой миграцией нельзя: правило 22b потребовало бы оставить
-- её с явным грантом service_role и включённым RLS, а в цепочке нет ни того ни
-- другого — и выпуск таких строк вслепую был бы непроверенной сменой привилегий
-- на живой таблице.
--
-- Права и RLS на appointments. Правило 22b требует: миграция, дотянувшаяся до
-- существующей таблицы, обязана оставить её с включённым RLS и явным грантом
-- service_role. Для appointments это уже сделала 032 после проверки, что
-- relrowsecurity = true; строки ниже повторяют её дословно и потому ничего не
-- меняют. Политик нет, а 023 и так отозвал права у anon и authenticated.
--
-- Всё аддитивно: ни одна существующая колонка не меняется, ни одно значение не
-- переписывается, каждый индекс и грант идемпотентен.

begin;

create table if not exists public.clinic_doctors (
  id uuid primary key default gen_random_uuid(),

  -- Чья это клиника. Каскад — как у всей цепочки 009+; workspaces заводится в
  -- 009 и остаётся единственным допустимым владельцем тенанта.
  workspace_id uuid not null references public.workspaces(id) on delete cascade,

  -- Кто это. Та же строка, которую форма записи положит снимком в
  -- appointments.doctor_name. Проверка на непустоту после btrim — не педантизм:
  -- имя из одних пробелов проходит NOT NULL, а потом все такие имена
  -- сталкиваются в уникальном индексе ниже; отказать в колонке дешевле, чем
  -- объяснять 23505.
  full_name text not null check (btrim(full_name) <> ''),

  -- «Кто он по профилю» — плоский текст, а не второй справочник. Ровно довод
  -- clinic_services.category: перечень из пяти-двадцати строк не стоит второго
  -- ресурса, второго экрана и записей в пяти реестрах.
  specialty text,

  -- Мост к сотруднику, если врач вообще заходит в систему. Nullable, потому что
  -- приезжий врач и врач без компьютера строки в staff_users не получат никогда,
  -- а карточка врача обязана существовать раньше логина. on delete set null, а
  -- не каскад: увольнение сотрудника не должно стирать врача, на которого
  -- смотрят сотни прошлых записей.
  staff_user_id uuid references public.staff_users(id) on delete set null,

  -- В каком порядке показывать в форме записи. То же имя и тот же смысл, что у
  -- clinic_services и lead_stages. Сервер отдаёт один ORDER BY без тай-брейка,
  -- поэтому при общем нуле порядок доопределяет браузер, сортируя по (sortOrder,
  -- full_name) русским коллятором.
  sort_order integer not null default 0,

  -- Убрать врача из выбора, не стирая историю. Единственная форма удаления,
  -- которая есть у платформы: маршрутизатор CRM не принимает DELETE ни для
  -- одного ресурса, и архивирование через PATCH isActive:false — записанное
  -- соглашение продукта.
  is_active boolean not null default true,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Единственный запрос списка: тенант плюс порядок. Третьей колонкой id — чтобы
-- выдача была устойчивой при равных sort_order.
create index if not exists clinic_doctors_workspace_sort_idx
  on public.clinic_doctors(workspace_id, sort_order, id);

-- То, ради чего справочник и заводится: «д-р Сауле» и «Д-р Сауле » перестают
-- быть двумя врачами — для новых записей. Индекс ЧАСТИЧНЫЙ, только по активным,
-- и это три свойства сразу: скрытый врач сохраняет своё имя, поэтому записи,
-- снявшие с него снимок, остаются читаемыми; завести врача заново после
-- архивирования можно; и уникальность живёт внутри клиники, а не поперёк всех.
-- Настоящему однофамильцу этот индекс откажет кодом 23505 — сервер обязан
-- перевести его в человеческую четырёхсотку, а не в «сбой сервиса».
create unique index if not exists clinic_doctors_workspace_active_name_idx
  on public.clinic_doctors(workspace_id, lower(btrim(full_name)))
  where is_active;

-- Один логин — не больше одного врача. Без этого будущее «мой график» не имело
-- бы однозначного ответа: два справочных врача указывали бы на одного человека.
create unique index if not exists clinic_doctors_workspace_staff_user_idx
  on public.clinic_doctors(workspace_id, staff_user_id)
  where staff_user_id is not null;

create table if not exists public.clinic_doctor_shifts (
  id uuid primary key default gen_random_uuid(),

  -- Тенант дублируется у ребёнка намеренно: каждый серверный запрос начинается с
  -- .eq("workspace_id", …), и правило не должно зависеть от join, которого в
  -- PostgREST-пути этого проекта нигде нет.
  workspace_id uuid not null references public.workspaces(id) on delete cascade,

  -- Чей это график. Каскад: строка графика без врача смысла не имеет.
  doctor_id uuid not null references public.clinic_doctors(id) on delete cascade,

  -- Недельный образец: 1 — понедельник, 7 — воскресенье, по ISO. Именно ISO, а
  -- не JS-нумерация: экран записей уже считает неделю с понедельника
  -- (getDay() || 7), и вторая нумерация в том же продукте — генератор ошибок.
  weekday smallint check (weekday is null or (weekday between 1 and 7)),

  -- Исключение на дату: выходной, отпуск, особые часы. Отпуск на две недели —
  -- ОДНА строка, а не четырнадцать, поэтому у даты есть конец. Один день —
  -- та же дата в обеих колонках; сервер проставляет конец сам, чтобы фильтр
  -- перекрытия был честным сравнением двух дат, а не coalesce, которого
  -- PostgREST не умеет.
  on_date date,
  on_date_end date,

  -- Как убрать часы. DELETE платформе недоступен, поэтому «не работает» — это
  -- значение, а не отсутствие строки: недельная строка с false равносильна
  -- отсутствию образца на этот день, строка на дату с false — выходной поверх
  -- образца.
  is_working boolean not null default true,

  -- Минуты от полуночи по времени КЛИНИКИ, а не time: интерпретировать их всё
  -- равно придётся в поясе клиники, и пояс обязан быть аргументом, а не
  -- догадкой. Конец может уехать за 1440 — смена 22:00-02:00 это [1320, 1560):
  -- ночной приём существует, а раскладывать его на две строки значит требовать
  -- от владельца арифметики в уме.
  start_minute integer,
  end_minute integer,

  -- «Отпуск», «Конференция» — для человека в ленте изменений. Свободный текст,
  -- поэтому в журнале он «факт», по общему правилу продукта.
  note text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  -- Ровно один ключ строки: либо день недели, либо дата. Одна таблица и два вида
  -- строк вместо двух таблиц — потому что разрешение вопроса «работает ли он в
  -- этот момент» читает их вместе, одним и тем же правилом.
  constraint clinic_doctor_shifts_one_key
    check ((weekday is null) <> (on_date is null)),

  -- Конец диапазона существует ровно тогда, когда есть начало, и не раньше него.
  constraint clinic_doctor_shifts_dates
    check (
      (on_date is null and on_date_end is null)
      or (on_date is not null and on_date_end is not null and on_date_end >= on_date)
    ),

  -- Выходной — это пустые часы, рабочая строка — это оба конца сразу. Начало
  -- всегда внутри суток; конец строго позже начала и не длиннее суток, иначе
  -- «смена» проглотила бы больше дня и перестала быть сменой.
  constraint clinic_doctor_shifts_minutes
    check (
      (is_working is false and start_minute is null and end_minute is null)
      or (
        is_working is true
        and start_minute is not null and end_minute is not null
        and start_minute >= 0 and start_minute < 1440
        and end_minute > start_minute and end_minute <= 2880
        and end_minute - start_minute <= 1440
      )
    )
);

-- Первый из двух запросов правила: недельный образец врача целиком. Он и есть
-- ответ на «задан ли график вообще» — пустой образец значит «правила нет», а не
-- «закрыто».
create index if not exists clinic_doctor_shifts_weekly_idx
  on public.clinic_doctor_shifts(workspace_id, doctor_id, weekday)
  where weekday is not null;

-- Второй: исключения, перекрывающие пару дат вокруг визита. Пара, а не одна
-- дата, потому что ночная смена предыдущего дня доживает до утра текущего.
create index if not exists clinic_doctor_shifts_dated_idx
  on public.clinic_doctor_shifts(workspace_id, doctor_id, on_date)
  where on_date is not null;

-- Связь визита с врачом. Nullable и не обязательна — дословно довод 032:
-- регистратор за стойкой не должен упираться в отсутствующую строку справочника,
-- поэтому свободный ввод в форме появляется как откат, а связь ставится, когда
-- врача выбрали из списка. Пустая у всей истории и остаётся пустой.
alter table public.appointments
  add column if not exists doctor_id uuid references public.clinic_doctors(id) on delete set null;

-- Запрос, ради которого колонка и заведена: «что у этого врача в этой клинике».
-- Частичный — строки без связи в него не входят и места не занимают, а сразу
-- после применения их все.
create index if not exists appointments_workspace_doctor_id_idx
  on public.appointments(workspace_id, doctor_id)
  where doctor_id is not null;

alter table public.clinic_doctors enable row level security;
alter table public.clinic_doctor_shifts enable row level security;
alter table public.appointments enable row level security;

revoke all on table public.clinic_doctors from anon, authenticated;
revoke all on table public.clinic_doctor_shifts from anon, authenticated;

-- DELETE в грантах нет намеренно: маршрутизатор такого метода не принимает, и
-- выдавать серверу возможность, до которой нельзя дотянуться, незачем.
grant select, insert, update
  on table public.clinic_doctors
  to service_role;

grant select, insert, update
  on table public.clinic_doctor_shifts
  to service_role;

grant select, insert, update
  on table public.appointments
  to service_role;

commit;
