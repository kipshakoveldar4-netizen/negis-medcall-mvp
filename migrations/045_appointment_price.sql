-- NEGIS Migration 045 — запись знает свою цену.
--
-- Владелец: «мастер видит свои услуги и цены, цены можно выбрать и
-- корректировать». До сих пор цена жила только в прайсе (clinic_services) и в
-- продажах: запись цену не несла вовсе, и «маникюр со скидкой за 4 000» нельзя
-- было выразить иначе, чем комментарием.
--
-- Цена — снимок на момент записи, как имя мастера и название услуги: прайс
-- потом подорожает, а этому клиенту обещали столько, сколько обещали. Поэтому
-- колонка, а не join с прайсом.
--
-- В тиынах, как везде (base_price_minor в 032): одна валюта хранения на всю
-- схему. bigint, как у прайса: integer кончается на 21,5 млн тенге, и цена
-- дорогой процедуры отвечала бы «сбоем сервиса» из самой базы. Nullable: у всей накопленной истории цены нет, и выдумывать её задним
-- числом нельзя.

begin;

alter table public.appointments
  add column if not exists price_minor bigint
    constraint appointments_price_minor_non_negative check (price_minor is null or price_minor >= 0);

commit;

notify pgrst, 'reload schema';
