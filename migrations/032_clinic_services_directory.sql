-- NEGIS Migration 032 — у услуги появляется своя строка, а у записи и продажи ссылка на неё.
--
-- Сегодня «услуга» в этом продукте — несколько несвязанных свободных строк.
-- Самая читаемая из них, appointments.service, пишется из тела запроса как есть,
-- а поле в форме записи — обычный текстовый ввод. Поэтому «Ботокс», «ботокс» и
-- «Ботокс лба» — три разные услуги в любом подсчёте; прайса, который клиника
-- могла бы править, нет вовсе; а выручка по услуге не вычисляется: deals
-- хранит сумму рядом со свободным заголовком, наполовину состоящим из названий
-- рекламных кампаний, скопированных из заявки.
--
-- Имя каталога — clinic_services, не services. Причина одна, и она проверена:
-- имя services жёстко перечислено в UNCREATED_LEGACY_TABLES набора
-- test:migration-chain, и M3 сравнивает этот набор через deepEqual — таблица с
-- таким именем в цепочке ломает набор по построению. Архивные миграции 001-006
-- упоминают services как объект совсем другой формы: он привязан к clinics,
-- несёт branch_id и правила бонусов. В production, вопреки строке в
-- docs/MIGRATIONS.md, объекта с таким именем НЕТ — проверено запросом
-- to_regclass перед применением, вернул NULL. Совпадения имён не будет ни при
-- каком прочтении, а тенантом остаётся workspaces, как у всей цепочки 009+.
--
-- Форма связи — снимок. Каталог владеет личностью услуги, а запись и продажа
-- хранят своё название на момент события: appointments.service и deals.title
-- остаются и ничем не переписываются. Так и должно быть — фильтр записей
-- строится по различным значениям этой колонки и сравнивает строки на
-- равенство, а журнал изменений печатает её словами. Переименование услуги не
-- переписывает мартовскую запись, а её архивирование не трогает ни одну
-- прошлую строку.
--
-- Никакого бэкфилла. appointments.service никогда не нормализовалась, поэтому
-- сопоставление по точному совпадению оставило бы большинство строк пустыми, а
-- «умное» приписало бы визиты не той услуге. Догадываться задним числом в
-- медицинских записях — не дело миграции. Старые строки живут со своим текстом
-- и service_id = NULL, и каждый экран продолжает показывать текст.
--
-- Права и RLS на appointments и deals. Правило 22b требует: миграция,
-- дотянувшаяся до существующей таблицы, обязана оставить её с включённым RLS и
-- явным грантом service_role. Перед применением проверено, что relrowsecurity
-- у обеих уже true, — значит строки включения ниже буквально ничего не меняют,
-- и привилегированного риска в этой миграции нет. Политик нет, поэтому anon и
-- authenticated остаются без доступа, а 023 и так отозвал у них права.
--
-- Всё здесь аддитивно: ни одна существующая колонка не меняется, ни одно
-- значение не переписывается, каждый индекс и грант идемпотентен.

begin;

create table if not exists public.clinic_services (
  id uuid primary key default gen_random_uuid(),

  -- Чей это прайс. Каскад — как у всех таблиц цепочки 009+; workspaces
  -- заводится в 009 и является единственным допустимым владельцем тенанта.
  workspace_id uuid not null references public.workspaces(id) on delete cascade,

  -- Как называется услуга. Ровно то, что сегодня набирают руками на каждом
  -- визите. Проверка на непустоту после btrim — не педантизм: имя из одних
  -- пробелов проходит NOT NULL, а потом все такие имена сталкиваются в
  -- уникальном индексе ниже; отказать в колонке дешевле, чем объяснять 23505.
  name text not null check (btrim(name) <> ''),

  -- «Сколько мы заработали на инъекционной косметологии». Плоский текст, а не
  -- ссылка на второй справочник: каталог из двадцати-шестидесяти строк не стоит
  -- второго ресурса, второго экрана и записей в четырёх реестрах. Путь наверх
  -- уже проложен в этом репозитории — 019 добавила leads.stage_id рядом с
  -- текстовым status; category_id, если понадобится, повторит ровно этот шаг.
  category text,

  -- Сколько стоит. Тиыны, потому что deals.amount_minor уже хранит деньги так и
  -- экран продаж уже так их печатает; второе представление денег в одном
  -- продукте — генератор ошибок. NULL и 0 — РАЗНЫЕ факты: NULL значит «цена не
  -- указана», 0 значит «бесплатно», и консультации за 0 ₸ клиники правда
  -- проводят. Поэтому колонка nullable и без default: иначе владелец в первый
  -- же день увидел бы «0 ₸» напротив каждой услуги, которую он ещё не оценил, —
  -- цифру, которой он не писал.
  base_price_minor bigint check (base_price_minor is null or base_price_minor >= 0),

  -- Сколько времени занимает — единственная колонка, которая меняет календарь.
  -- Сейчас сервер приводит любую незаданную длительность к 60 минутам, и на
  -- этой догадке считается пересечение слотов. NULL сохраняет сегодняшние 60.
  -- Потолок 600 — с запасом: окно поиска пересечений равно суткам, и
  -- длительность, дотягивающаяся до его края, заставила бы проверку молча
  -- пропускать наложения. Десятичасовых визитов не бывает, а зазор между 600 и
  -- 1440 — именно то, ради чего ограничение и ставится.
  duration_minutes integer check (duration_minutes is null or (duration_minutes > 0 and duration_minutes <= 600)),

  -- Что это за процедура: текст для карточки услуги, а позже — согласованная
  -- формулировка для контент-студии, которая сегодня раскладывает одну
  -- нетипизированную строку брифа в десять полей выдачи.
  description text,

  -- В каком порядке показывать в форме записи. Тот же смысл и то же имя, что у
  -- lead_stages и lead_sources. Сервер отдаёт один ORDER BY без тай-брейка,
  -- поэтому при общем нуле порядок доопределяет браузер, сортируя по
  -- (sortOrder, name).
  sort_order integer not null default 0,

  -- Убрать услугу из выбора, не стирая историю. Единственная форма удаления,
  -- которая есть у платформы: маршрутизатор CRM не принимает DELETE ни для
  -- одного ресурса, и архивирование через PATCH isActive:false — записанное
  -- соглашение продукта.
  is_active boolean not null default true,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Единственный запрос списка: тенант плюс порядок. Третьей колонкой id — чтобы
-- выдача была устойчивой при равных sort_order.
create index if not exists clinic_services_workspace_sort_idx
  on public.clinic_services(workspace_id, sort_order, id);

-- То, ради чего справочник и заводится: «Ботокс» и «ботокс » перестают быть
-- двумя услугами. Индекс ЧАСТИЧНЫЙ — только по активным строкам, и это три
-- разных свойства сразу: скрытая услуга сохраняет своё имя, поэтому записи,
-- снявшие с неё снимок, остаются читаемыми; завести услугу заново после
-- архивирования можно, а не упереться в невидимую строку; и уникальность живёт
-- внутри клиники, а не поперёк всех.
create unique index if not exists clinic_services_workspace_active_name_idx
  on public.clinic_services(workspace_id, lower(btrim(name)))
  where is_active;

-- Связь визита с услугой. Nullable и не обязательна: регистратор за стойкой не
-- должен упираться в отсутствующую строку каталога, поэтому свободный ввод в
-- форме остаётся, а связь ставится, когда услугу выбрали из списка.
alter table public.appointments
  add column if not exists service_id uuid references public.clinic_services(id) on delete set null;

-- Связь продажи с услугой — то, ради чего выручка по услуге вообще становится
-- вычислимой: сегодня оплаченные продажи складываются без единого измерения, а
-- экран сводки прямо отказывается группировать, потому что честного измерения
-- не существует. amount_minor не трогается: это снимок того, сколько реально
-- заплатили, и каталог никогда не становится источником истины для уже
-- прошедших денег.
alter table public.deals
  add column if not exists service_id uuid references public.clinic_services(id) on delete set null;

-- Запрос, который эти колонки и заводились обслуживать: «что по этой услуге в
-- этой клинике». Частичные — строки без связи в него не входят и места в
-- индексе не занимают, а сразу после применения их большинство.
create index if not exists appointments_workspace_service_idx
  on public.appointments(workspace_id, service_id)
  where service_id is not null;

create index if not exists deals_workspace_service_idx
  on public.deals(workspace_id, service_id)
  where service_id is not null;

alter table public.clinic_services enable row level security;
alter table public.appointments enable row level security;
alter table public.deals enable row level security;

revoke all on table public.clinic_services from anon, authenticated;

-- DELETE в грантах нет намеренно: маршрутизатор такого метода не принимает, и
-- выдавать серверу возможность, до которой нельзя дотянуться, незачем.
grant select, insert, update
  on table public.clinic_services
  to service_role;

grant select, insert, update
  on table public.appointments
  to service_role;

grant select, insert, update
  on table public.deals
  to service_role;

commit;
