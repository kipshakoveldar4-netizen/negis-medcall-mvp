-- NEGIS Migration 036 — у мастера появляется ёмкость.
--
-- Проверка пересечений записей считает конфликтом ЛЮБОЕ наложение интервалов у
-- одного исполнителя и выходит по первому же совпадению. Для врача это верно:
-- приём один, и второй пациент в тот же интервал — ошибка.
--
-- Для салона это неверно. Мастер ведёт двух клиентов параллельно постоянно:
-- одному нанесена краска и он сидит выдерживает, второму в это время делают
-- укладку. Сегодня такая запись возможна только через «Сохранить всё равно», и
-- у этого две беды сразу. Первая: обход снимает проверку ЦЕЛИКОМ, то есть
-- настоящая двойная запись в то же кресло тоже перестаёт ловиться. Вторая:
-- каждая такая запись пишется в журнал как перезапись — рутина салона
-- становится неотличима от сознательного нарушения, и настоящее нарушение в
-- этом шуме уже не найти.
--
-- Отсюда колонка: сколько клиентов исполнитель ведёт одновременно.
--
-- Умолчание — единица, и это главное свойство миграции. Всем существующим
-- строкам она даёт ровно сегодняшнее поведение: врач как вёл одного пациента,
-- так и ведёт, ни одна клиника ничего не заметит. Салон поднимает число там,
-- где это правда, и получает проверку, которая работает, вместо проверки,
-- которую приходится обходить.
--
-- Потолок в CHECK стоит не ради базы, а ради оператора: ёмкость в сто человек
-- — это не настройка, а опечатка, и лучше отказать сразу, чем потом искать,
-- почему проверка пересечений молчит.

begin;

alter table public.clinic_doctors
  add column if not exists capacity smallint not null default 1;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'clinic_doctors_capacity_check'
  ) then
    alter table public.clinic_doctors
      add constraint clinic_doctors_capacity_check
      check (capacity between 1 and 12);
  end if;
end $$;

-- Служебная роль уже имеет права на эту таблицу (033), новая колонка отдельного
-- гранта не требует: права в Postgres выдаются на таблицу целиком.

commit;
