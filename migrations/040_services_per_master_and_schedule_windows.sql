-- NEGIS Migration 040 — у услуги появляется хозяин, у графика — закрытые окна.
--
-- Две задачи владельца салона, обе из живой работы, и обе упираются в схему.
--
-- ЗАДАЧА 1. «Услуги мастера по отдельности». В салоне одиннадцать мастеров и
-- сто пятнадцать услуг, и это НЕ общий прайс: у Айданы глубокое бикини стоит
-- 5 000, у Аружан то же самое — 6 000; ламинирование бровей у Айданы 6 000, у
-- Амины 10 000. Один прайс на клинику здесь не «упрощение», а неправда,
-- которая попадёт в чек клиента.
--
-- Форма хранения — хозяин у строки прайса, а не отдельная таблица связей.
-- Связка «услуга + мастер + своя цена» дала бы ту же цену через join, но ценой
-- второго ресурса, второго экрана и правки в четырёх реестрах — при том что
-- списки мастеров почти не пересекаются: у найл-стилиста девятнадцать своих
-- строк, у визажиста три своих. Прайс салона — это набор личных прайсов, и
-- схема теперь говорит ровно это.
--
-- doctor_id NULL остаётся законным значением: это общая услуга клиники,
-- видимая у всех. Весь сегодняшний прайс останется общим — миграция ничего не
-- раздаёт мастерам сама и ничего не удаляет.
--
-- on delete set null, а не cascade: карточку мастера в этом продукте не
-- удаляют (единственная форма удаления — is_active = false), но если это
-- когда-нибудь случится, потерять вместе с ней прайс на девятнадцать строк
-- хуже, чем увидеть эти строки общими.
--
-- ЗАДАЧА 2. «Если мастер отдыхает — закрыть окно или целый день». Целый день и
-- отпуск график умеет с 033: строка is_working = false без часов. Окна внутри
-- дня он не умеет — CHECK 033 прямо запрещает часы у нерабочей строки. Из-за
-- этого «уехала с 14 до 16» приходилось изображать разрывом смены: удалить
-- рабочую строку и завести две. Теперь нерабочая строка МОЖЕТ нести часы, и
-- это читается как перерыв: сервер вычитает её из рабочих интервалов.
--
-- Ни одна применённая миграция здесь не переписывается. Индекс 032 и CHECK 033
-- заменяются новыми — это forward-изменение, а не правка истории: старое
-- правило перестаёт быть верным ровно потому, что продукт изменился.

begin;

-- ── 1. Хозяин строки прайса ──────────────────────────────────────────────

alter table public.clinic_services
  add column if not exists doctor_id uuid references public.clinic_doctors(id) on delete set null;

-- Уникальность имени теперь живёт внутри ПРАЙСА МАСТЕРА, а не всей клиники.
-- Без этой замены «Коррекция бровей» существовала бы в салоне ровно один раз,
-- а её делают четверо: Еркеназ, Бану, Айдана и Амина — каждая за свои деньги.
--
-- coalesce на нулевой uuid — не украшение: в обычном индексе NULL-ы считаются
-- различными, и две общие услуги с одним именем прошли бы обе. Сентинел
-- возвращает то свойство, ради которого индекс 032 и заводился.
drop index if exists public.clinic_services_workspace_active_name_idx;

create unique index if not exists clinic_services_workspace_owner_name_idx
  on public.clinic_services(
    workspace_id,
    coalesce(doctor_id, '00000000-0000-0000-0000-000000000000'::uuid),
    lower(btrim(name))
  )
  where is_active;

-- Запрос, ради которого колонка и заведена: «прайс этого мастера». Частичный —
-- общие услуги в него не входят и места не занимают.
create index if not exists clinic_services_workspace_doctor_idx
  on public.clinic_services(workspace_id, doctor_id, sort_order, id)
  where doctor_id is not null;

-- ── 2. Закрытое окно внутри дня ──────────────────────────────────────────

-- Старое правило: у нерабочей строки часов быть не может. Новое: у нерабочей
-- строки часов может не быть (весь день закрыт) ИЛИ они есть (закрыто окно).
-- Проверки самих часов — те же, что и были, и остаются одинаковыми для обоих
-- видов строк: конец строго позже начала, сутки — потолок длины.
alter table public.clinic_doctor_shifts
  drop constraint if exists clinic_doctor_shifts_minutes;

alter table public.clinic_doctor_shifts
  add constraint clinic_doctor_shifts_minutes check (
    (start_minute is null and end_minute is null and is_working is false)
    or (
      start_minute is not null and end_minute is not null
      and start_minute >= 0 and start_minute < 1440
      and end_minute > start_minute and end_minute <= 2880
      and end_minute - start_minute <= 1440
    )
  );

commit;

-- PostgREST держит схему в кэше; на Supabase перечитывание запускает встроенный
-- триггер на DDL, и эта строка нужна там, где триггера нет. Лишней не бывает.
notify pgrst, 'reload schema';
