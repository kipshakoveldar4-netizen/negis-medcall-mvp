-- NEGIS Migration 041 — напоминание клиенту о записи.
--
-- Владелец салона: «нужно оповещение клиентов до прихода — что у них
-- запланирована запись в наш салон». Это не «отправить сообщение»: отправка
-- без памяти о том, что уже отправлено, шлёт человеку одно и то же по кругу
-- при каждом запуске рабочего цикла. Память и заводится здесь.
--
-- reminder_sent_at — МЕТКА ВРЕМЕНИ, а не флаг. Флаг отвечает «да», а метка
-- отвечает «когда»: если клиент говорит «мне пришло в три ночи», разобрать это
-- можно только по метке. Она же делает повторную отправку видимой в данных, а
-- не только в логе.
--
-- Колонка nullable и без значения по умолчанию: у всей накопленной истории
-- напоминаний не было, и проставить им «отправлено» задним числом значило бы
-- соврать. Пустая метка читается как «не отправляли».
--
-- Индекс — под единственный запрос рабочего цикла: «чьи визиты скоро, и кому
-- ещё не писали». Частичный, потому что отправленные из выборки уходят
-- навсегда, и держать их в индексе незачем.

begin;

alter table public.appointments
  add column if not exists reminder_sent_at timestamptz;

create index if not exists appointments_reminder_due_idx
  on public.appointments(workspace_id, starts_at)
  where reminder_sent_at is null;

commit;

notify pgrst, 'reload schema';
