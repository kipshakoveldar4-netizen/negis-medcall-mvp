-- NEGIS Migration 043 — запись помнит, кто её завёл.
--
-- Владелец салона уточнил правило контактов, и оно перестало быть «роль видит
-- или не видит»: «мастера могут записывать своих клиентов и видеть их номера,
-- но в записях, которые заводят админы, номера им не видно».
--
-- То есть видимость телефона зависит от АВТОРА записи, а не только от роли
-- смотрящего. Своего клиента мастер привёл сам — прятать от него номер,
-- который он же и вписал, бессмысленно. Клиента клиники, записанного
-- ресепшном, мастер видит по работе: имя, время, услуга — но номер остаётся у
-- тех, кто отвечает за звонки.
--
-- Автора взять неоткуда: appointments не хранят создателя. Журнал изменений
-- (029) знает событие «created» и актора, но опираться на него в правиле
-- видимости нельзя — журнал ведётся с оговорками (пишется после успеха,
-- переживает отказы, чистится по сроку хранения), и правило доступа,
-- зависящее от ленты событий, становится негерметичным ровно там, где ленты
-- не оказалось.
--
-- Колонка nullable: у всей накопленной истории автора нет, и выдумывать его
-- задним числом нельзя. Пустой автор читается как «завела клиника» — то есть
-- по строгому варианту правила, без телефона у мастера. Это осознанный выбор
-- в пользу более закрытого поведения там, где мы не знаем правды.
--
-- on delete set null: увольнение сотрудника не должно ни удалять запись, ни
-- ронять её; авторство просто становится неизвестным.

begin;

alter table public.appointments
  add column if not exists created_by_staff_user_id uuid
    references public.staff_users(id) on delete set null;

-- Запрос правила видимости: «мои ли это записи». Частичный — строки без
-- автора в него не входят и места не занимают, а сразу после применения их
-- большинство.
create index if not exists appointments_created_by_idx
  on public.appointments(workspace_id, created_by_staff_user_id)
  where created_by_staff_user_id is not null;

commit;

notify pgrst, 'reload schema';
