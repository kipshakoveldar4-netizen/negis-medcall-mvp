-- ── ШАГ 3. Кого удалось найти в справочнике ──────────────────────────────
-- Совпадение ищется в два захода.
--
-- Сначала по имени: если ЖИВАЯ карточка с таким именем одна, вопросов нет.
-- Архивная того же имени не считается — удалять карточки продукт не умеет, и
-- принимать архив за второго мастера значило бы не залить прайс тому, кто в
-- справочнике один.
--
-- Если живых карточек с этим именем две (в салоне две Дильназ — найл-стилист
-- и визажист), имя людей не различает, и решает СПЕЦИАЛЬНОСТЬ: короткое слово
-- из прайса ищется в тексте специальности карточки. Не нашлось или нашлось у
-- обеих — строка не заливается и мастер называется в отчёте. Отдать прайс
-- наугад нельзя: найл-услуги у визажиста — это неверный чек клиента.
create temporary table seed_match on commit drop as
with living as (
  select d.id, d.full_name, lower(coalesce(d.specialty, '')) as specialty
  from public.clinic_doctors d
  where d.workspace_id = (select workspace_id from seed_ctx) and d.is_active
),
named as (
  select s.master_name, s.service_name, s.price_tenge,
         lower(btrim(s.spec_key)) as spec_key,
         l.id as doctor_id, l.specialty,
         count(*) over (partition by s.master_name, s.service_name) as same_name
  from seed_prices s
  join living l on lower(btrim(l.full_name)) = lower(btrim(s.master_name))
),
picked as (
  select *
  from named
  where same_name = 1
     or (spec_key <> '' and position(spec_key in specialty) > 0)
)
select p.master_name, p.service_name, p.price_tenge, p.doctor_id
from picked p
where (
  select count(*) from picked p2
  where p2.master_name = p.master_name and p2.service_name = p.service_name
) = 1;

-- ── ШАГ 4. Залить ────────────────────────────────────────────────────────
insert into public.clinic_services (workspace_id, doctor_id, name, base_price_minor, sort_order, is_active)
select
  (select workspace_id from seed_ctx),
  m.doctor_id,
  m.service_name,
  -- Колонка хранит ТИЫНЫ (см. 032): тенге умножаются на сто. Без множителя
  -- весь прайс салона оказался бы в базе в сто раз дешевле, а собственный
  -- отчёт скрипта показал бы владельцу присланные им же числа.
  (m.price_tenge::bigint * 100),
  row_number() over (partition by m.doctor_id order by m.service_name),
  true
from seed_match m
on conflict do nothing;

update public.clinic_services cs
set base_price_minor = m.price_tenge::bigint * 100,
    updated_at = now()
from seed_match m
where cs.workspace_id = (select workspace_id from seed_ctx)
  and cs.doctor_id = m.doctor_id
  and lower(btrim(cs.name)) = lower(btrim(m.service_name))
  and cs.base_price_minor is distinct from m.price_tenge::bigint * 100;

-- ── ШАГ 5. Отчёт: кого НЕ залили и почему ────────────────────────────────
select
  s.master_name as "мастер",
  case
    when (select count(*) from public.clinic_doctors d
          where d.workspace_id = (select workspace_id from seed_ctx)
            and lower(btrim(d.full_name)) = lower(btrim(s.master_name))
            and d.is_active) = 0
      then 'карточки нет в справочнике — заведите её и запустите скрипт снова'
    else 'две карточки с этим именем, и специальность их не различает — впишите специальность (например nail и визажист) и запустите снова'
  end as "почему пропущен",
  count(*) as "услуг не залито"
from seed_prices s
where not exists (select 1 from seed_match m where m.master_name = s.master_name)
group by 1, 2
order by 1;

-- ── ШАГ 6. Что получилось ────────────────────────────────────────────────
select d.full_name as "мастер",
       count(*) as "услуг",
       min(cs.base_price_minor) / 100 as "от, ₸",
       max(cs.base_price_minor) / 100 as "до, ₸"
from public.clinic_services cs
join public.clinic_doctors d on d.id = cs.doctor_id
where cs.workspace_id = (select workspace_id from seed_ctx) and cs.is_active
group by d.full_name
order by d.full_name;

