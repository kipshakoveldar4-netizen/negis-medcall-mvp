-- ── ШАГ 3. Кого удалось найти в справочнике ──────────────────────────────
create temporary table seed_match on commit drop as
select s.master_name, s.service_name, s.price_tenge, d.id as doctor_id
from seed_prices s
join public.clinic_doctors d
  on d.workspace_id = (select workspace_id from seed_ctx)
 and lower(btrim(d.full_name)) = lower(btrim(s.master_name))
 and d.is_active
where (
  -- Считаются только ЖИВЫЕ карточки. Архивная карточка того же имени — обычная
  -- история (удалять их продукт не умеет), и принимать её за второго мастера
  -- значило бы не залить прайс человеку, который в справочнике ровно один.
  select count(*) from public.clinic_doctors d2
  where d2.workspace_id = (select workspace_id from seed_ctx)
    and lower(btrim(d2.full_name)) = lower(btrim(s.master_name))
    and d2.is_active
) = 1;

-- ── ШАГ 4. Залить ────────────────────────────────────────────────────────
insert into public.clinic_services (workspace_id, doctor_id, name, base_price_minor, sort_order, is_active)
select
  (select workspace_id from seed_ctx),
  m.doctor_id,
  m.service_name,
  -- Колонка хранит ТИЫНЫ (см. 032): тенге умножаются на сто. Без множителя
  -- весь прайс салона оказался бы в базе в сто раз дешевле, а собственный
  -- отчёт скрипта показал бы владельцу присланные им же числа.
  (m.price_tenge::bigint * 100),
  row_number() over (partition by m.doctor_id order by m.service_name),
  true
from seed_match m
on conflict do nothing;

update public.clinic_services cs
set base_price_minor = m.price_tenge::bigint * 100,
    updated_at = now()
from seed_match m
where cs.workspace_id = (select workspace_id from seed_ctx)
  and cs.doctor_id = m.doctor_id
  and lower(btrim(cs.name)) = lower(btrim(m.service_name))
  and cs.base_price_minor is distinct from m.price_tenge::bigint * 100;

-- ── ШАГ 5. Отчёт: кого НЕ залили и почему ────────────────────────────────
select
  s.master_name as "мастер",
  case
    when (select count(*) from public.clinic_doctors d
          where d.workspace_id = (select workspace_id from seed_ctx)
            and lower(btrim(d.full_name)) = lower(btrim(s.master_name))
            and d.is_active) = 0
      then 'карточки нет в справочнике — заведите её и запустите скрипт снова'
    else 'в справочнике ДВЕ карточки с этим именем — переименуйте их по-разному и запустите снова'
  end as "почему пропущен",
  count(*) as "услуг не залито"
from seed_prices s
where not exists (select 1 from seed_match m where m.master_name = s.master_name)
group by 1, 2
order by 1;

-- ── ШАГ 6. Что получилось ────────────────────────────────────────────────
select d.full_name as "мастер",
       count(*) as "услуг",
       min(cs.base_price_minor) / 100 as "от, ₸",
       max(cs.base_price_minor) / 100 as "до, ₸"
from public.clinic_services cs
join public.clinic_doctors d on d.id = cs.doctor_id
where cs.workspace_id = (select workspace_id from seed_ctx) and cs.is_active
group by d.full_name
order by d.full_name;

commit;
