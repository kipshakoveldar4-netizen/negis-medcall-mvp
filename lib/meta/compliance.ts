/** Названо эстетическое состояние: у клиники — замечание, у салона — норма. */
const AESTHETIC_CONDITION: Rule = {
  code: "aesthetic_condition",
  severity: "review",
  pattern: phrase("акне|постакне|морщин\\p{L}*|пигментац\\p{L}*"),
  message: "Названо эстетическое состояние — уберите обращение к читателю рядом с ним.",
};

/**
 * Заявление о лечении.
 *
 * У клиники это замечание: она вправе говорить «лечение». У салона — отказ, и
 * это УЖЕСТОЧЕНИЕ, а не послабление. Салон, обещающий вылечить, заявляет
 * услугу, которой не оказывает, и отвечать за это будет он.
 *
 * «излечени» перечислено отдельно, а не снято левой границей: «болезн» живёт
 * внутри «безболезненная процедура» — обычной фразы косметологии, которую
 * блокировать не за что.
 */
function treatmentClaim(vertical: Vertical): Rule {
  return {
    code: "medical_treatment_claim",
    severity: vertical === "beauty" ? "block" : "review",
    pattern: phrase(
      "заболеван\\p{L}*|болезн\\p{L}*|диагноз\\p{L}*|лечени\\p{L}*|излечени\\p{L}*|вылечим|избавиться",
    ),
    message:
      vertical === "beauty"
        ? "Салон не лечит: слова про лечение и диагноз в рекламу ставить нельзя."
        : "Названо лечение или диагноз — уберите обращение к читателю рядом с ним.",
  };
}

function disclaimerRule(vertical: Vertical): Rule {
  const words = vertical === "beauty" ? "консультац|подбер|мастер" : "консультац|индивидуальн|специалист";
  return {
    code: "missing_disclaimer",
    severity: "review",
    // Прежняя версия была `^((?!…).)*$` — точка не переходит через перевод
    // строки, а три поля объявления склеиваются именно им, поэтому у объявления
    // из двух и более полей правило не срабатывало вообще.
    pattern: new RegExp(`^(?:(?!${words})[\\s\\S])*$`, "i"),
    message:
      vertical === "beauty"
        ? "Добавьте оговорку о том, что результат подбирается индивидуально."
        : "Добавьте нейтральный дисклеймер о консультации специалиста.",
  };
}

/**
 * Набор правил для ниши.
 *
 * У салона нет правила про эстетическое состояние — и это главное изменение.
 * «Морщины» и «пигментация» для него не диагноз, а название того, что он делает.
 * Замечание было неустранимым, но попадало в счётчик, по которому переписывание
 * выбирает лучший вариант, — то есть продукт вознаграждал тот вариант, из
 * которого услуга ВЫЧЕРКНУТА.
 */
export function rulesFor(vertical: Vertical): Rule[] {
  const rules = [...SHARED_RULES, treatmentClaim(vertical)];
  if (vertical === "clinic") rules.push(AESTHETIC_CONDITION);
  rules.push(disclaimerRule(vertical));
  return rules;
}

function uniqueIssues(issues: MetaComplianceIssue[]) {
  const seen = new Set<string>();
  return issues.filter((issue) => {
    if (seen.has(issue.code)) return false;
    seen.add(issue.code);
    return true;
  });
}

// Замены — с теми же границами, что и правила выше, и по той же причине.
//
// В исходной версии здесь стояло `\b`, поэтому на кириллице не срабатывала ни
// одна из них: «безопасная версия» была точной копией исходного текста с
// приклеенным дисклеймером. Экран запуска рекламы показывал эту копию под
// заголовком «Безопасная версия» и кнопкой «Принять безопасную версию».
//
// Порядок значим: длинные фразы идут раньше своих частей, иначе «избавиться
// от» съело бы хвост «хотите избавиться от» и первая замена не нашла бы себя.
const rewrites: Array<[string, string, string]> = [
  // [что ищем, замена со строчной, замена с прописной]
  ["хотите избавиться от", "доступна консультация по вопросам", "Доступна консультация по вопросам"],
  ["избавиться от", "получить консультацию по вопросам", "Получить консультацию по вопросам"],
  ["у вас", "для клиентов", "Для клиентов"],
  ["гарантируем", "помогаем подобрать", "Помогаем подобрать"],
  ["навсегда", "", ""],
  ["100\\s*%", "", ""],
  ["без риска", "после консультации", "После консультации"],
  ["лечение", "консультация", "Консультация"],
  ["вылечим", "проведем консультацию", "Проведем консультацию"],
  // Три написания одного и того же: в исходной таблице был только первый, а
  // блокирующее правило ловит все три.
  ["до\\s*/\\s*после", "индивидуальный план", "Индивидуальный план"],
  ["до и после", "индивидуальный план", "Индивидуальный план"],
  ["before\\s*/\\s*after", "индивидуальный план", "Индивидуальный план"],
];

function applyRewrite(text: string, rule: [string, string, string]): string {
  const [needle, lower, upper] = rule;
  return text.replace(
    new RegExp(`${EDGE_BEFORE}(${needle})${EDGE_AFTER}`, "giu"),
    (_match, before: string, word: string) => `${before}${/^\p{Lu}/u.test(word) ? upper : lower}`,
  );
}

/**
 * Уборка после замен.
 *
 * Часть замен пустые («навсегда», «100 %»), и вычеркнутое слово оставляет за
 * собой не только лишний пробел, но и знак препинания, который к нему
 * относился. Раньше подчищались только пробелы, поэтому «Быстро, навсегда,
 * дёшево.» превращалось в «Быстро,, дёшево.», а «Результат — навсегда —
 * гарантируем.» — в «Результат — — помогаем подобрать.». Дальше такой обрубок
 * проверялся заново, запрещённых слов в нём, разумеется, не находилось, и
 * экран называл его безопасной версией.
 */
function tidy(text: string): string {
  return text
    // Пробелы: двойные внутри строки и лишний перед знаком.
    .replace(/[^\S\n]{2,}/g, " ")
    .replace(/[^\S\n]+([.,!?;:…])/g, "$1")
    // Один и тот же знак дважды подряд — след вычеркнутого слова между ними.
    .replace(/([.,!?;:—–-])(?:[^\S\n]*\1)+/g, "$1")
    // Запятая, повисшая перед точкой: «Быстро,.» → «Быстро.»
    .replace(/[,;:][^\S\n]*([.!?…])/g, "$1")
    // Строка, начавшаяся со знака: вычеркнули её первое слово.
    .replace(/(^|\n)[^\S\n]*[,;:—–-]+[^\S\n]*/g, "$1")
    // Пробелы по краям каждой строки, а не только всего текста: поля
    // объявления склеиваются переводом строки, и висящий пробел перед ним
    // уезжал бы в Meta вместе с текстом.
    .replace(/[^\S\n]+(\n|$)/g, "$1")
    .replace(/(^|\n)[^\S\n]+/g, "$1")
    .trim();
}

/** Есть ли в строке хоть одна буква или цифра. */
function hasContent(text: string): boolean {
  return /[\p{L}\p{N}]/u.test(text);
}

/** Замены по одному полю объявления — без дисклеймера и без подстановки. */
function rewriteField(text: string): string {
  return tidy(rewrites.reduce(applyRewrite, text));
}

function rewriteText(text: string, disclaimer: string): string {
  const normalized = rewriteField(text);

  // Пустой считается и строка из одних знаков препинания: «Навсегда!» после
  // замены — это «!», и выдавать такое за текст объявления нельзя.
  const safe = hasContent(normalized)
    ? normalized
    : "Консультация специалиста в клинике. Подберем индивидуальный план после диагностики.";
  return safe.toLowerCase().includes("консультац") || safe.toLowerCase().includes("индивидуальн")
    ? `${safe}\n\n${disclaimer}`
    : `${safe}\n\nЗапишитесь на консультацию. ${disclaimer}`;
}

function evaluate(text: string, rules: Rule[]): { status: MetaComplianceStatus; issues: MetaComplianceIssue[] } {
  const issues = uniqueIssues(
    rules.flatMap((rule) => {
      const match = text.match(rule.pattern);
      return match
        ? [
            {
              code: rule.code,
              severity: rule.severity,
              message: rule.message,
              // Вторая группа — сама фраза. У правила про дисклеймер групп нет,
              // и там остаётся match[0]: оно и означает «во всём тексте».
              match: match[2] ?? match[0],
            },
          ]
        : [];
    }),
  );
  const hasBlocked = issues.some((issue) => issue.severity === "block");
  const hasReview = issues.some((issue) => issue.severity === "review");

  return { status: hasBlocked ? "blocked" : hasReview ? "needs_review" : "safe", issues };
}

export function checkMetaCompliance(
  input: { text?: string; headline?: string; description?: string },
  vertical: Vertical = DEFAULT_VERTICAL,
): MetaComplianceResult {
  const rules = rulesFor(vertical);
  const disclaimer = DISCLAIMERS[vertical];
  const text = [input.headline, input.text, input.description].filter(Boolean).join("\n").trim();
  const verdict = evaluate(text, rules);
  const safeText = rewriteText(text, disclaimer);
  // Тем же набором правил — по переписанному тексту. Иначе «безопасная версия»
  // остаётся обещанием, за которое никто не отвечает.
  const safeVerdict = evaluate(safeText, rules);

  return {
    status: verdict.status,
    issues: verdict.issues,
    safeText,
    safeTextStatus: safeVerdict.status,
    safeTextIssues: safeVerdict.issues,
    safeParts: {
      headline: rewriteField(input.headline || ""),
      text: rewriteField(input.text || ""),
      description: rewriteField(input.description || ""),
    },
    disclaimer,
  };
}
