  beauty: "Результат зависит от исходных данных. Подберём вариант на консультации.",
  // Стоматология — медицинская ниша: оговорка та же, что у клиники. Своя
  // формулировка здесь была бы выдумкой: правила рекламы для неё те же.
  dental: "Результаты индивидуальны. Перед процедурой нужна консультация стоматолога.",
