/**
 * Правила пароля — одни и те же на сервере и в браузере.
 *
 * Раньше их было двое: сервер требовал 8 символов (validateOwnerPassword), а
 * форма профиля в кабинете — 6. Сотрудник ставил себе шестизначный пароль, и
 * тот работал: Supabase проверяет только свой минимум. Расхождение опаснее, чем
 * кажется, — админ раздаёт пароли по нашим правилам, а сам сотрудник тут же
 * ослабляет их, и никто этого не видит.
 *
 * Модуль намеренно без зависимостей от Node: TextEncoder есть и в браузере, и в
 * Node 18+, а Buffer в бандл Vite не попадает.
 */

/** Предел bcrypt, которым Supabase хэширует пароли. Длиннее молча обрезается. */
const MAX_PASSWORD_BYTES = 72;

/** Наш минимум. Supabase по умолчанию пускает и 6 — нам этого мало. */
const MIN_PASSWORD_CHARS = 8;

export const PASSWORD_RULE_HINT = "Не короче 8 символов, без пробелов по краям.";

/**
 * Возвращает список претензий к паролю по-русски. Пустой список — пароль
 * годится. Байты, а не символы: кириллическая буква занимает два.
 */
export function validatePasswordRules(value: unknown): string[] {
  const password = typeof value === "string" ? value : "";
  const details: string[] = [];
  if (password.length < MIN_PASSWORD_CHARS) details.push("Пароль — не короче 8 символов.");
  if (new TextEncoder().encode(password).length > MAX_PASSWORD_BYTES) {
    details.push("Пароль слишком длинный: до 72 байт, кириллическая буква считается за две.");
  }
  if (password.trim().length === 0 && password.length > 0) details.push("Пароль из одних пробелов не защищает.");
  // Хвостовой пробел от вставки из чата невидим на экране результата, а при
  // передаче голосом или с бумажки теряется гарантированно — человек упрётся
  // в «Invalid login credentials», неотличимо от «пароль неверный».
  else if (password !== password.trim()) {
    details.push("Пароль начинается или кончается пробелом — уберите его: при передаче он потеряется.");
  }
  return details;
}
