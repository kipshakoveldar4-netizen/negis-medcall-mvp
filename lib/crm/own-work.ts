/**
 * Мастер видит свою работу, а не всю клинику.
 *
 * Владелец: «мастера не должны видеть контактные данные клиентов, только имя и
 * время записи» — и следом: записи должны быть ТОЛЬКО СВОИ. Первую половину
 * закрывает lib/crm/contact-privacy.ts (срезает поля), эта — вторую (сужает
 * сам набор строк).
 *
 * Почему предикат отдельный, а не тот же, что у контактов. Сегодня обе роли —
 * это doctor, и соблазн переиспользовать один список велик. Но правила разные
 * по смыслу: «не показывать телефон» останется верным и для регистратора
 * подменной смены, а «показывать только свои записи» для регистратора неверно
 * и сломает ему работу. Один список на два правила означал бы, что расширение
 * одного молча меняет другое.
 *
 * Почему совпадение по имени, а не только по ссылке. appointments.doctor_id
 * появился в 033 и у всей накопленной истории пуст: миграция намеренно ничего
 * не заполняла (см. её шапку). Сузить выдачу только по ссылке — значит показать
 * мастеру пустой календарь там, где у него сорок записей. Поэтому связь И имя,
 * и оба варианта имени: карточка справочника и учётная запись сотрудника.
 */

/** Роли, которым видна только их собственная работа. */
const OWN_WORK_ONLY_ROLES = new Set(["doctor"]);

export function seesOnlyOwnWork(role: unknown): boolean {
  return typeof role === "string" && OWN_WORK_ONLY_ROLES.has(role);
}

/**
 * Кто такой этот мастер с точки зрения записи: ссылка на карточку справочника
 * и имена, под которыми он мог быть записан свободным текстом.
 */
export type OwnWorkIdentity = {
  doctorId: string;
  names: string[];
  /**
   * Хоть одно чтение личности не удалось.
   *
   * Разница между «мастер ни с кем не связан» и «мы не смогли это выяснить»
   * стоит рабочего дня: в первом случае пустой календарь — правда, во втором
   * это молчаливая ложь, после которой человек уходит домой.
   */
  readFailed?: boolean;
};

/** Пустая личность — ни ссылки, ни имени. Ей не принадлежит ничего. */
export function isEmptyIdentity(identity: OwnWorkIdentity): boolean {
  return !identity.doctorId && identity.names.length === 0;
}

function normalizeName(value: unknown): string {
  return typeof value === "string" ? value.trim().toLowerCase() : "";
}

/**
 * Принадлежит ли строка этому мастеру.
 *
 * Сравнение имён без учёта регистра и краевых пробелов — ровно так же, как это
 * делает проверка пересечений (она сравнивает doctor_name строками, и «айгуль»
 * с «Айгуль » для неё один человек). Разойтись с ней значило бы получить
 * защиту от двойной записи, считающую по одному правилу, и видимость — по
 * другому.
 */
/**
 * Указывает ли строка ТОЛЬКО на самого мастера.
 *
 * Это не то же самое, что rowBelongsTo, и подмена одного другим была дырой.
 * «Принадлежит» — вопрос ИЛИ: строка моя, если совпала ссылка ИЛИ имя, потому
 * что у истории до 033 ссылки нет вовсе. «Целится в меня» — вопрос И: если
 * названа ссылка, она обязана быть моей, и если названо имя, оно обязано быть
 * моим. Иначе правка, меняющая ОДНО поле, проходит на совпадении второго:
 * мастер оставлял свою ссылку и переписывал имя на коллегу — а этим же ходом
 * открывался перебор чужого дня через отказ «слот занят».
 */
export function rowTargetsOnlySelf(row: Record<string, unknown>, identity: OwnWorkIdentity): boolean {
  const id = typeof row.doctor_id === "string" ? row.doctor_id : "";
  const name = normalizeName(row.doctor_name);
  if (id && id !== identity.doctorId) return false;
  if (name && !identity.names.some((mine) => normalizeName(mine) === name)) return false;
  // Ни ссылки, ни имени — цель не названа вовсе. Для гейта это «нечего
  // проверять», и решение принимает вызывающий, а не молчаливое «да».
  return Boolean(id || name);
}

export function rowBelongsTo(row: Record<string, unknown>, identity: OwnWorkIdentity): boolean {
  if (identity.doctorId && typeof row.doctor_id === "string" && row.doctor_id === identity.doctorId) return true;
  const name = normalizeName(row.doctor_name);
  if (!name) return false;
  return identity.names.some((mine) => normalizeName(mine) === name);
}
